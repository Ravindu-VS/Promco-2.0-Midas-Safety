import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';

const BRAND = [190, 23, 29];
const GREY = [110, 110, 110];

const loadImage = (src) =>
  new Promise((resolve) => {
    const img = new Image();
    img.onload = () => {
      try {
        const canvas = document.createElement('canvas');
        canvas.width = img.naturalWidth;
        canvas.height = img.naturalHeight;
        canvas.getContext('2d').drawImage(img, 0, 0);
        resolve({ data: canvas.toDataURL('image/png'), width: img.naturalWidth, height: img.naturalHeight });
      } catch (e) {
        resolve(null);
      }
    };
    img.onerror = () => resolve(null);
    img.src = src;
  });

const fmt = (value) => (value ? new Date(value).toLocaleString() : '—');

async function createDocument({ title, subtitle, orientation = 'portrait' }) {
  const doc = new jsPDF({ orientation, unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();

  const logo = await loadImage(`${process.env.PUBLIC_URL || ''}/logo-light.png`);
  if (logo) {
    const h = 12;
    doc.addImage(logo.data, 'PNG', 14, 10, (logo.width / logo.height) * h, h);
  }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(...BRAND);
  doc.text('Promco 2.0', pageWidth - 14, 15, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...GREY);
  doc.text('Midas Safety – Maintenance Platform', pageWidth - 14, 20, { align: 'right' });

  doc.setDrawColor(...BRAND);
  doc.setLineWidth(0.6);
  doc.line(14, 25, pageWidth - 14, 25);

  doc.setTextColor(20, 20, 20);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text(title, 14, 34);
  if (subtitle) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(...GREY);
    doc.text(subtitle, 14, 40);
  }
  return { doc, y: subtitle ? 46 : 40 };
}

function addFooters(doc) {
  const pages = doc.getNumberOfPages();
  const w = doc.internal.pageSize.getWidth();
  const h = doc.internal.pageSize.getHeight();
  for (let i = 1; i <= pages; i += 1) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(...GREY);
    doc.text(`Generated by Promco 2.0 on ${new Date().toLocaleString()}`, 14, h - 8);
    doc.text(`Page ${i} of ${pages}`, w - 14, h - 8, { align: 'right' });
  }
}

const tableTheme = {
  theme: 'grid',
  headStyles: { fillColor: BRAND, textColor: 255, fontStyle: 'bold' },
  styles: { fontSize: 8.5, cellPadding: 2, overflow: 'linebreak' },
  alternateRowStyles: { fillColor: [248, 245, 245] },
  margin: { left: 14, right: 14, bottom: 16 },
};

function section(doc, y, heading, head, body, emptyText, columnStyles) {
  const pageHeight = doc.internal.pageSize.getHeight();
  if (y > pageHeight - 40) {
    doc.addPage();
    y = 20;
  }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11.5);
  doc.setTextColor(...BRAND);
  doc.text(heading, 14, y);
  y += 3;
  if (!body.length) {
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(9);
    doc.setTextColor(...GREY);
    doc.text(emptyText, 14, y + 5);
    return y + 13;
  }
  autoTable(doc, { ...tableTheme, startY: y, head: [head], body, columnStyles });
  return doc.lastAutoTable.finalY + 9;
}

/** Daily operations report built from GET /api/reports/daily. */
export async function downloadDailyReportPdf(report) {
  const dateLabel = new Date(`${report.date}T00:00:00`).toLocaleDateString(undefined, {
    weekday: 'long', year: 'numeric', month: 'long', day: 'numeric',
  });
  const { doc, y: startY } = await createDocument({
    title: 'Daily Operations Report',
    subtitle: `${dateLabel}  ·  Prepared for ${report.generatedBy.username} (${report.generatedBy.role})`,
  });
  let y = startY;
  const s = report.summary;

  autoTable(doc, {
    ...tableTheme,
    startY: y,
    head: [['Summary', 'Value']],
    body: [
      ['Fault reports raised this day', s.faultsReported],
      ['Faults resolved this day', s.faultsResolved],
      ['Maintenance jobs scheduled for this day', s.maintenanceScheduled],
      ['Maintenance jobs completed this day', s.maintenanceCompleted],
      [`Recorded actions (${report.activityScope})`, s.activityCount],
      ['Users active this day', s.activeUsers],
      ['Machines registered (now)', s.machinesTotal],
      ['Open faults (now)', s.openFaultsNow],
    ],
    columnStyles: { 0: { cellWidth: 120 }, 1: { halign: 'right', fontStyle: 'bold' } },
  });
  y = doc.lastAutoTable.finalY + 4;
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8);
  doc.setTextColor(...GREY);
  doc.text('"(now)" figures reflect the state when this report was generated, not the end of the selected day.', 14, y + 2);
  y += 10;

  y = section(doc, y, 'Machine status (now)',
    ['Machine', 'Code', 'Status', 'Open faults'],
    report.machines.map((m) => [m.name, m.code, m.status, m.openFaults]),
    'No machines have been registered.');

  y = section(doc, y, 'Fault reports raised',
    ['#', 'Machine', 'Priority', 'Status', 'Description', 'Reported by', 'Time'],
    report.faultsReported.map((f) => [f.id, f.machine, f.priority, f.status, f.description, f.reportedByName, fmt(f.reportedAt)]),
    'No faults were reported on this day.',
    { 0: { cellWidth: 9 }, 6: { cellWidth: 32 } });

  y = section(doc, y, 'Faults resolved',
    ['#', 'Machine', 'Resolved by', 'Resolution notes', 'Time'],
    report.faultsResolved.map((f) => [f.id, f.machine, f.resolvedByName || '—', f.resolutionNotes || '—', fmt(f.resolvedAt)]),
    'No faults were resolved on this day.',
    { 0: { cellWidth: 9 }, 4: { cellWidth: 34 } });

  y = section(doc, y, 'Maintenance',
    ['#', 'Machine', 'Type', 'Status', 'Technician', 'Scheduled', 'Completed', 'Description'],
    report.maintenance.map((m) => [m.id, m.machine, m.maintenanceType, m.status, m.technicianName || '—',
      m.scheduledDate, fmt(m.completedAt), m.description]),
    'No maintenance was scheduled for or completed on this day.',
    { 0: { cellWidth: 9 }, 6: { cellWidth: 30 } });

  section(doc, y, `Activity log (${report.activityScope})`,
    ['Time', 'User', 'Action', 'Details'],
    report.activity.map((a) => [new Date(a.timestamp).toLocaleTimeString(), a.username, a.action, a.summary]),
    'No activity was recorded on this day.',
    { 0: { cellWidth: 24 }, 1: { cellWidth: 30 }, 2: { cellWidth: 20 } });

  addFooters(doc);
  doc.save(`promco-daily-report-${report.date}.pdf`);
}

/** Exports the rows currently shown in a table (columns: [{ header, value(row) }]). */
export async function downloadTablePdf({ title, columns, rows, filterText }) {
  const landscape = columns.length > 6;
  const { doc, y } = await createDocument({
    title,
    subtitle: `${rows.length} record(s)${filterText ? ` matching "${filterText}"` : ''}`,
    orientation: landscape ? 'landscape' : 'portrait',
  });
  autoTable(doc, {
    ...tableTheme,
    startY: y,
    head: [columns.map((c) => c.header)],
    body: rows.map((r) => columns.map((c) => {
      const v = c.value(r);
      return v === null || v === undefined || v === '' ? '—' : String(v);
    })),
  });
  addFooters(doc);
  doc.save(`${title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.pdf`);
}
